from __future__ import annotations

import os
import runpy
from pathlib import Path

from setuptools import setup
from setuptools.command.bdist_wheel import bdist_wheel as _bdist_wheel
from setuptools.command.build_py import build_py as _build_py

# version.py at the project root is the single version source. It is plain
# data, so reading it never imports the package or its compiled payload.
VERSION = runpy.run_path(str(Path(__file__).resolve().parent / "version.py"))


class build_py(_build_py):
    """Generate the runtime mlc_doxygen_bin/_version.py from version.py."""

    def run(self) -> None:
        super().run()
        target = Path(self.build_lib) / "mlc_doxygen_bin" / "_version.py"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            "# Generated by setup.py from version.py; do not edit.\n"
            f"__version__ = {VERSION['__version__']!r}\n"
            f"DOXYGEN_VERSION = {VERSION['DOXYGEN_VERSION']!r}\n"
            f"DOXYGEN_TAG = {VERSION['DOXYGEN_TAG']!r}\n",
            encoding="utf-8",
        )


class bdist_wheel(_bdist_wheel):
    def finalize_options(self) -> None:
        super().finalize_options()
        self.root_is_pure = False
        plat_name = os.environ.get("MLC_DOXYGEN_BIN_PLAT_NAME")
        if plat_name:
            self.plat_name = plat_name
            self.plat_name_supplied = True

    def get_tag(self) -> tuple[str, str, str]:
        _python, _abi, plat = super().get_tag()
        return "py3", "none", plat


setup(
    version=VERSION["__version__"],
    cmdclass={
        "build_py": build_py,
        "bdist_wheel": bdist_wheel,
    },
)
